#include <stdio.h>
#include <locale.h>
#include <malloc.h>


int main()
{
    setlocale(0, "");
    setlocale(LC_NUMERIC, "C");

    printf("\n------------------------------------------------------------------------\n");

    int n;
    do{
        printf("\nВведите количество элементов n: ");
        scanf("%d", &n);
        if (n <= 0 || n > 100){
            printf("\n========================================================================\n\t\t");
            printf("Ошибка: нарушен диапазон входных данных");
            printf("\n========================================================================\n");
        }
    }while (n <= 0 || n > 100);

    printf("\n------------------------------------------------------------------------\n");

    int x;
    do{
        printf("\nВведите число x для проверки кратности: ");
        scanf("%d", &x);
        if (x <= 0 || x > 1000){
            printf("\n========================================================================\n\t\t");
            printf("Ошибка: нарушен диапазон входных данных");
            printf("\n========================================================================\n");
        }
    }while (x <= 0 || x > 1000);

    printf("\n------------------------------------------------------------------------\n");

    int *A, i;
    A = (int*) malloc(n * sizeof(int));
    printf("\nВведите элементы массива A:\n");
    for (i = 0; i<n ; i++){
        printf("\nA[%d]: ", i);
        scanf("%d", &A[i]);
    }

    printf("\n------------------------------------------------------------------------\n");

    printf("\nВведено количество элементов n: %d\n", n);
    printf("Введено число x для проверки кратности: %d\n", x);
    printf("Введены элементы массива A: [ %d", A[0]);
    for (i = 1; i < n; i++){
        printf("; %d", A[i]);
    }
    printf(" ]\n");



//обработка
    int flag = 1;
    i = (n-1);
    while ( (i>=0) && flag){
        if (A[i] % x != 0){
            flag = 0;
        }else i--;
    }

    printf("\n========================================================================\n\n\t\t\t");
    printf("Результат\n\n\t\t");
    if (flag){
        printf("Все элементы массива кратны x");
    }else{
        printf("Найден элемент, некратный x, его номер: %d", i);
    }
    printf("\n\n========================================================================\n");

    free(A);

    return 0;
}


















